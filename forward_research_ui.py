# ============================================================

def _render_threshold_sweep(
    result,
):

    st.subheader(
        "4. Swing Score + Intraday Score Research Grid"
    )

    st.caption(
        "This isolates the two main scores without forcing every other "
        "gate. It helps test whether 85/85 is historically useful or "
        "simply restrictive."
    )

    sweep = _safe_df(
        result.get(
            "threshold_sweep"
        )
    )

    if sweep.empty:

        st.info(
            "No threshold-sweep results are available."
        )

        return

    minimum_sample = st.slider(
        "Minimum observations for threshold ranking",
        min_value=5,
        max_value=100,
        value=20,
        step=5,
        key="v37_min_threshold_sample",
    )

    horizon = st.selectbox(
        "Threshold comparison horizon",
        [
            1,
            3,
            5,
            10,
            20,
        ],
        index=3,
        key="v37_threshold_horizon",
    )

    mean_column = (
        f"{horizon}d_mean_pct"
    )

    median_column = (
        f"{horizon}d_median_pct"
    )

    win_column = (
        f"{horizon}d_win_rate_pct"
    )

    sample_column = (
        f"{horizon}d_n"
    )

    filtered = sweep.copy()

    if sample_column in filtered.columns:

        sample_values = pd.to_numeric(
            filtered[
                sample_column
            ],
            errors="coerce",
        ).fillna(
            0
        )

        filtered = filtered[
            sample_values
            >= minimum_sample
        ].copy()

    elif "observations" in filtered.columns:

        sample_values = pd.to_numeric(
            filtered[
                "observations"
            ],
            errors="coerce",
        ).fillna(
            0
        )

        filtered = filtered[
            sample_values
            >= minimum_sample
        ].copy()

    if filtered.empty:

        st.warning(
            "No score combinations meet the selected minimum sample size."
        )

    else:

        sort_columns = []
        ascending = []

        if mean_column in filtered.columns:

            filtered[
                "_rank_mean"
            ] = pd.to_numeric(
                filtered[
                    mean_column
                ],
                errors="coerce",
            )

            sort_columns.append(
                "_rank_mean"
            )

            ascending.append(
                False
            )

        if sample_column in filtered.columns:

            sort_columns.append(
                sample_column
            )

            ascending.append(
                False
            )

        elif "observations" in filtered.columns:

            sort_columns.append(
                "observations"
            )

            ascending.append(
                False
            )

        if sort_columns:

            filtered = filtered.sort_values(
                sort_columns,
                ascending=ascending,
                na_position="last",
            )

        filtered = filtered.drop(
            columns=[
                "_rank_mean"
            ],
            errors="ignore",
        )

        st.markdown(
            f"#### Highest historical "
            f"{horizon}-session mean returns"
        )

        _display_table(
            filtered,
            columns=[
                "swing_threshold",
                "intraday_threshold",
                "observations",
                "observation_rate_pct",
                sample_column,
                mean_column,
                median_column,
                win_column,
                "20d_mfe_pct",
                "20d_mae_pct",
            ],
            head=30,
        )

        best = filtered.iloc[
            0
        ]

        best_sample = best.get(
            sample_column,
            best.get(
                "observations",
                0,
            ),
        )

        st.info(
            "Highest-ranked combination under this descriptive screen: "
            f"Swing Score ≥ **{_number(best.get('swing_threshold'), 1)}**, "
            f"Intraday Score ≥ **{_number(best.get('intraday_threshold'), 1)}**. "
            f"Sample: **{int(best_sample or 0):,}**. "
            f"Mean {horizon}-session return: "
            f"**{_pct(best.get(mean_column))}**. "
            f"Positive-return rate: "
            f"**{_pct(best.get(win_column))}**."
        )

        st.warning(
            "This is not permission to change production thresholds. "
            "Any candidate setting still needs out-of-sample testing "
            "and portfolio replay."
        )

    with st.expander(
        "Show entire threshold sweep"
    ):

        _display_table(
            sweep
        )


