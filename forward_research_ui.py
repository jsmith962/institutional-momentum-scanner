def render_forward_research_lab(
    backtest_result: dict,
    daily_bars: pd.DataFrame,
):

    st.header(
        "v3.7 Gate Bottleneck + Forward Return Analyzer"
    )

    st.caption(
        "Research only. The live production scanner remains unchanged."
    )

    st.info(
        "v3.7 studies what happened after each historical scanner "
        "observation and measures whether the rules that block trades "
        "were historically associated with better future outcomes."
    )

    if not isinstance(
        backtest_result,
        dict,
    ):

        st.warning(
            "Run the production backtest first."
        )

        return

    signal_log = _safe_df(
        backtest_result.get(
            "signal_log"
        )
    )

    if signal_log.empty:

        st.warning(
            "The production backtest does not contain a usable "
            "historical signal audit."
        )

        return

    if (
        daily_bars is None
        or not isinstance(
            daily_bars,
            pd.DataFrame,
        )
        or daily_bars.empty
    ):

        st.warning(
            "Historical daily bars are required to calculate forward returns."
        )

        st.info(
            "Run the $2,000 backtest again after app.py stores "
            "daily_history in Streamlit session state."
        )

        return

    # ========================================================
    # DATASET SUMMARY
    # ========================================================

    st.subheader(
        "Historical Research Dataset"
    )

    c1, c2, c3 = st.columns(
        3
    )

    c1.metric(
        "Signal observations",
        f"{len(signal_log):,}",
    )

    c2.metric(
        "Historical daily bars",
        f"{len(daily_bars):,}",
    )

    symbol_count = (
        signal_log[
            "symbol"
        ].nunique()
        if "symbol"
        in signal_log.columns
        else 0
    )

    c3.metric(
        "Symbols represented",
        f"{symbol_count:,}",
    )

    st.warning(
        "This study covers the symbols and historical periods contained "
        "in the backtest. It is not a complete reconstruction of the "
        "entire historical U.S. equity universe."
    )

    # ========================================================
    # RUN CONTROL
    # ========================================================

    run = st.button(
        "RUN v3.7 FORWARD-RETURN RESEARCH",
        type="primary",
        width="stretch",
        key="run_v37_forward_research",
    )

    if run:

        status = st.status(
            "Building historical forward-return research dataset...",
            expanded=True,
        )

        progress = st.progress(
            0
        )

        try:

            status.write(
                "1/3 Matching scanner observations to future daily prices..."
            )

            progress.progress(
                15
            )

            enriched = attach_forward_returns(
                signal_log,
                daily_bars,
            )

            if (
                not isinstance(
                    enriched,
                    pd.DataFrame,
                )
                or enriched.empty
            ):

                status.update(
                    label=(
                        "No forward-return observations "
                        "could be constructed."
                    ),
                    state="error",
                )

                st.error(
                    "No usable forward-return dataset was created. "
                    "Check that signal_log and daily_history contain "
                    "matching symbols and dates."
                )

                return

            progress.progress(
                55
            )

            status.write(
                "2/3 Reconstructing production gates and bottlenecks..."
            )

            result = run_forward_gate_research(
                enriched
            )

            progress.progress(
                90
            )

            status.write(
                "3/3 Building score buckets, threshold sweep "
                "and near-miss research..."
            )

            st.session_state[
                "v37_forward_research_result"
            ] = result

            st.session_state[
                "v37_enriched_signal_log"
            ] = enriched

            progress.progress(
                100
            )

            status.update(
                label="v3.7 forward-return research complete.",
                state="complete",
                expanded=False,
            )

        except Exception as exc:

            status.update(
                label="v3.7 research stopped because of an error.",
                state="error",
                expanded=True,
            )

            st.exception(
                exc
            )

            return

    # ========================================================
    # SAVED RESULTS
    # ========================================================

    result = st.session_state.get(
        "v37_forward_research_result"
    )

    enriched_signal_log = st.session_state.get(
        "v37_enriched_signal_log"
    )

    if not isinstance(
        result,
        dict,
    ):

        st.info(
            "Run the v3.7 forward-return research above."
        )

        return

    if result.get(
        "status"
    ) != "COMPLETE":

        st.warning(
            result.get(
                "message",
                "Forward research did not complete.",
            )
        )

        return

    st.divider()

    st.success(
        result.get(
            "message",
            "v3.7 research complete.",
        )
    )

    summary = result.get(
        "summary",
        {},
    )

    if not bool(
        summary.get(
            "forward_returns_available",
            False,
        )
    ):

        st.warning(
            "Gate diagnostics were created, but usable forward-return "
            "observations were not detected. Re-run the backtest and "
            "then rerun v3.7 research."
        )

    # ========================================================
    # RESEARCH OUTPUT
    # ========================================================

    _render_summary(
        result
    )

    st.divider()

    _render_bottlenecks(
        result
    )

    st.divider()

    _render_gate_forward_returns(
        result
    )

    st.divider()

    _render_score_buckets(
        result
    )

    st.divider()

    _render_threshold_sweep(
        result
    )

    st.divider()

    _render_single_gate_near_misses(
        result
    )

    st.divider()

    _render_production_survivors(
        result
    )

    st.divider()

    _render_downloads(
        result,
        enriched_signal_log,
    )

    st.divider()

