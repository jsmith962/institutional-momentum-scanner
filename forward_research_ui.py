def _safe_df(value):

    if isinstance(
        value,
        pd.DataFrame,
    ):
        return value

    return pd.DataFrame()


def _number(
    value,
    digits=2,
):

    try:

        if value is None or pd.isna(value):
            return "—"

        value = float(
            value
        )

        if digits == 0:
            return f"{value:,.0f}"

        return f"{value:,.{digits}f}"

    except Exception:

        return "—"


def _pct(
    value,
    digits=2,
):

    try:

        if value is None or pd.isna(value):
            return "—"

        return f"{float(value):,.{digits}f}%"

    except Exception:

        return "—"


def _display_table(
    frame,
    columns=None,
    head=None,
):

    df = _safe_df(
        frame
    ).copy()

    if df.empty:

        st.info(
            "No data is available for this section."
        )

        return

    if columns:

        available = [
            column
            for column in columns
            if column in df.columns
        ]

        if available:

            df = df[
                available
            ]

    if head is not None:

        df = df.head(
            int(
                head
            )
        )

    st.dataframe(
        df,
        width="stretch",
        hide_index=True,
    )


# ============================================================
# TOP SUMMARY
# ============================================================

def _render_summary(
    result,
):

    summary = (
        result.get(
            "summary",
            {},
        )
        if isinstance(
            result,
            dict,
        )
        else {}
    )

    observations = int(
        summary.get(
            "observations",
            0,
        )
        or 0
    )

    forward_observations = int(
        summary.get(
            "forward_observations",
            0,
        )
        or 0
    )

    single_gate_near_misses = int(
        summary.get(
            "single_gate_near_misses",
            0,
        )
        or 0
    )

    largest_recovered = int(
        summary.get(
            "largest_recovered_if_removed",
            0,
        )
        or 0
    )

    c1, c2, c3, c4 = st.columns(
        4
    )

    c1.metric(
        "Historical observations",
        f"{observations:,}",
    )

    c2.metric(
        "Forward-return observations",
        f"{forward_observations:,}",
    )

    c3.metric(
        "Single-gate near misses",
        f"{single_gate_near_misses:,}",
    )

    c4.metric(
        "Recovered if largest gate removed",
        f"{largest_recovered:,}",
    )

    largest_label = summary.get(
        "largest_bottleneck_label"
    )

    if largest_label:

        st.info(
            f"Largest leave-one-gate-out bottleneck: "
            f"**{largest_label}**"
        )

    best_gate = summary.get(
        "best_10d_gate_label"
    )

    best_edge = summary.get(
        "best_10d_edge_pct"
    )

    if (
        best_gate
        and best_edge is not None
    ):

        st.success(
            "Strongest descriptive 10-session gate association: "
            f"**{best_gate}** with a mean pass-vs-fail edge of "
            f"**{_pct(best_edge)}**."
        )

    weakest_gate = summary.get(
        "weakest_10d_gate_label"
    )

    weakest_edge = summary.get(
        "weakest_10d_edge_pct"
    )

    if (
        weakest_gate
        and weakest_edge is not None
    ):

        st.warning(
            "Weakest descriptive 10-session gate association: "
            f"**{weakest_gate}** with a mean pass-vs-fail edge of "
            f"**{_pct(weakest_edge)}**."
        )


