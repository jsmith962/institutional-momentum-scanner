# GATE FORWARD RETURNS
# ============================================================

def _render_gate_forward_returns(
    result,
):

    st.subheader(
        "2. Did Each Gate Historically Add Value?"
    )

    st.caption(
        "This compares forward returns for observations that passed each "
        "gate versus observations that failed it. Positive edge means the "
        "pass group had the better historical average. This is association "
        "research only."
    )

    frame = _safe_df(
        result.get(
            "gate_forward_returns"
        )
    )

    if frame.empty:

        st.info(
            "No forward-return gate analysis is available."
        )

        return

    _display_table(
        frame,
        columns=[
            "gate_label",
            "passed_n",
            "failed_n",
            "1d_mean_edge_pct",
            "3d_mean_edge_pct",
            "5d_mean_edge_pct",
            "10d_mean_edge_pct",
            "20d_mean_edge_pct",
            "5d_win_rate_edge_pct",
            "10d_win_rate_edge_pct",
            "20d_pass_mfe_pct",
            "20d_fail_mfe_pct",
            "20d_pass_mae_pct",
            "20d_fail_mae_pct",
        ],
    )

    if "10d_mean_edge_pct" not in frame.columns:

        return

    valid = frame.dropna(
        subset=[
            "10d_mean_edge_pct"
        ]
    )

    if valid.empty:

        return

    best = (
        valid
        .sort_values(
            "10d_mean_edge_pct",
            ascending=False,
        )
        .iloc[
            0
        ]
    )

    weakest = (
        valid
        .sort_values(
            "10d_mean_edge_pct",
            ascending=True,
        )
        .iloc[
            0
        ]
    )

    c1, c2 = st.columns(
        2
    )

    with c1:

        st.success(
            "Strongest positive association: "
            f"**{best.get('gate_label', 'Unknown')}**"
        )

        st.write(
            "10-day mean edge: "
            f"**{_pct(best.get('10d_mean_edge_pct'))}**"
        )

        st.write(
            "10-day win-rate edge: "
            f"**{_pct(best.get('10d_win_rate_edge_pct'))}**"
        )

    with c2:

        st.warning(
            "Weakest association: "
            f"**{weakest.get('gate_label', 'Unknown')}**"
        )

        st.write(
            "10-day mean edge: "
            f"**{_pct(weakest.get('10d_mean_edge_pct'))}**"
        )

        st.write(
            "10-day win-rate edge: "
            f"**{_pct(weakest.get('10d_win_rate_edge_pct'))}**"
        )


